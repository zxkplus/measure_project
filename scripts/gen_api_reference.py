"""Generate machine-derived API reference tables from the live code paths.

Hand-written endpoint docs drift from the implementation, and the drift is silent:
a reader cannot tell a stale table from a current one.  This script renders the
parts of the documentation that are pure functions of the code — object-type
contracts for v1/v2 and the complete v2 HTTP surface — into Markdown files that a
test then pins byte-for-byte (see ``tests/test_generated_api_docs.py``).

Usage:
    python scripts/gen_api_reference.py            # write generated docs
    python scripts/gen_api_reference.py --check    # exit 1 if on disk differs
    python scripts/gen_api_reference.py --stdout   # print, do not write

Only the *generated* sections belong here.  Prose that the code cannot express —
state-machine ordering, tuning advice, error recovery — stays hand-written in
``measure_api/measure-api/references/``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from measure.object_specs import OBJECT_SPECS  # noqa: E402
from measure_api.schemas import (  # noqa: E402
    TYPE_COMPATIBILITY,
    accepts_result_type,
    primitive_types,
)

GENERATED_DIR = ROOT / "measure_api" / "measure-api" / "references" / "generated"
BANNER = (
    "<!-- AUTO-GENERATED by scripts/gen_api_reference.py — do not edit.\n"
    "     Regenerate: python scripts/gen_api_reference.py\n"
    "     Pinned by:  tests/test_generated_api_docs.py -->\n\n"
)


def _fmt(value: Any) -> str:
    """Render one default value the way JSON would."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        text = f"{value:.6f}".rstrip("0").rstrip(".")
        return text or "0"
    if isinstance(value, (list, tuple)):
        return json.dumps(list(value), separators=(", ", ": "))
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def _accepts(expected: str, actual: str) -> bool:
    return accepts_result_type(expected, actual)


def object_contracts_md() -> str:
    """Render the shared object-type contract table used by v1 and v2."""
    primitives = [OBJECT_SPECS[t] for t in sorted(primitive_types())]
    composed = [OBJECT_SPECS[t] for t in sorted(
        o.object_type for o in OBJECT_SPECS.values() if o.is_composed)]

    lines: List[str] = [
        "# Object Contracts (generated)",
        "",
        "Derived from `measure/object_specs.py` — the single registry behind the",
        "GUI, API v1 and API v2. If a type is not listed here it does not exist.",
        "",
        "## Primitive types",
        "",
        "| Type | Result | Required params | Optional params (default) |",
        "|---|---|---|---|",
    ]
    for spec in primitives:
        optional = ", ".join(f"`{k}`({_fmt(v)})" for k, v in spec.defaults.items()) or "—"
        lines.append(
            f"| `{spec.object_type}` | {spec.result_type} | "
            f"{', '.join(f'`{p}`' for p in spec.required)} | {optional} |"
        )

    lines += [
        "",
        "## Composed types",
        "",
        "A composed type takes no tuning parameters, only dependencies. Dependency",
        "values are **labels**, not ids.",
        "",
        "| Type | Result | Dependency slot | Slot accepts result types |",
        "|---|---|---|---|",
    ]
    for spec in composed:
        for i, (param, expected) in enumerate(spec.deps):
            accepted = ", ".join(sorted(
                f"`{t}`" for t in TYPE_COMPATIBILITY.get(expected, {expected})))
            head = (f"| `{spec.object_type}` | {spec.result_type} |"
                    if i == 0 else "| | |")
            lines.append(f"{head} `{param}` | {accepted} |")

    lines += [
        "",
        "### Why a circle may feed a point slot",
        "",
        "`CircleResult` exposes `row`/`col` as documented compatibility aliases for",
        "`center_row`/`center_col`, so a fitted circle is a valid point source. The",
        "shipped models rely on this. The reverse is never true — a point cannot",
        "feed a `circle_label` slot.",
        "",
        "### EdgePair endpoints are addressable, the pair itself is not",
        "",
        "A **valid** `EdgePair` publishes only `<label>_A` and `<label>_B` (its two",
        "detected edges); its bare label appears solely as an invalid placeholder",
        "when the pair fails. So a bare EdgePair label is not a resolvable",
        "dependency. This mirrors the GUI's dependency picker, which offers the two",
        "endpoints and deliberately omits the centre.",
        "",
        "## Parameter keys accepted by every type",
        "",
        "| Type | All accepted parameter keys |",
        "|---|---|",
    ]
    for spec in sorted(OBJECT_SPECS.values(), key=lambda s: s.object_type):
        keys = ", ".join(f"`{k}`" for k in spec.param_keys) or "—"
        lines.append(f"| `{spec.object_type}` | {keys} |")
    lines.append("")
    return "\n".join(lines)


def _schema_inline(node: Dict[str, Any], depth: int = 0) -> str:
    """Compact one-line rendering of a JSON-schema fragment."""
    if not isinstance(node, dict):
        return "any"
    if "const" in node:
        return f"const {_fmt(node['const'])}"
    if "allOf" in node or "oneOf" in node or "anyOf" in node:
        parts = node.get("allOf") or node.get("oneOf") or node.get("anyOf")
        return " | ".join(_schema_inline(p, depth) for p in parts)
    if "$ref" in node:
        return f"[{node['$ref'].rsplit('/', 1)[-1]}]"
    kind = node.get("type", "any")
    if kind == "object":
        props = node.get("properties", {})
        required = set(node.get("required", []))
        inner = ", ".join(
            f"{k}{'*' if k in required else ''}: {_schema_inline(v, depth + 1)}"
            for k, v in list(props.items())[:12])
        more = ", …" if len(props) > 12 else ""
        extra = "" if node.get("additionalProperties", True) else " (+unknown rejected)"
        return "{" + (f" {inner}{more} " if inner else "") + "}" + extra
    if kind == "array":
        return f"array<{_schema_inline(node.get('items', {}), depth)}>"
    if "enum" in node:
        return " | ".join(f"`{_fmt(e)}`" for e in node["enum"])
    hints = "".join(f" ({node[k]})" for k in ("format",) if k in node)
    return kind + hints


def v2_surface_md() -> str:
    """Render the whole v2 HTTP surface from the app's own OpenAPI document."""
    from measure_api.v2.application import EngineApplication
    from measure_api.v2.http import create_production_app

    app = create_production_app(EngineApplication(str(ROOT / "output" / "_docgen")))
    with app.test_client() as client:
        doc = client.get("/api/v2/openapi.json").get_json()

    schemas = doc.get("components", {}).get("schemas", {})
    lines: List[str] = [
        "# Measure API v2 — Endpoint Surface (generated)",
        "",
        "Captured from `GET /api/v2/openapi.json`, served by the code itself. This",
        "is the authoritative v2 contract; the hand-written v1 reference in",
        "`../api_reference.md` does not describe these routes.",
        "",
        f"Paths: **{len(doc['paths'])}** · Schemas: **{len(schemas)}**",
        "",
        "## Endpoints",
        "",
        "| Method | Path | Request body | Success responses |",
        "|---|---|---|---|",
    ]
    for path, item in sorted(doc["paths"].items()):
        for method, op in sorted(item.items()):
            if method not in ("get", "post", "put", "delete"):
                continue
            ref = None
            content = (op.get("requestBody") or {}).get("content", {}).get("application/json", {})
            sch = content.get("schema", {})
            if "$ref" in sch:
                ref = sch["$ref"].rsplit("/", 1)[-1]
            elif sch:
                ref = _schema_inline(sch)
            codes = sorted(c for c in op.get("responses", {}) if c.isdigit())
            lines.append(
                f"| `{method.upper()}` | `{path}` | "
                f"{('`' + ref + '`') if ref else '—'} | {', '.join(codes) or '—'} |")

    lines += [
        "",
        "## Schemas",
        "",
        "`*` marks a required property. Objects reject unknown fields unless noted.",
        "",
    ]
    for name in sorted(schemas):
        node = schemas[name]
        variants = node.get("oneOf") or node.get("anyOf")
        lines.append(f"### `{name}`")
        lines.append("")
        if variants:
            tags = [v.get("properties", {}).get("object_type", {}).get("const")
                    for v in variants]
            tags = [t for t in tags if t]
            if tags:
                lines.append(f"Union over {len(variants)} variants"
                             + (f" (`object_type`: {', '.join('`%s`' % t for t in tags)})"))
            else:
                lines.append(f"Union of {len(variants)} variants.")
            for v in variants:
                lines.append(f"- {_schema_inline(v)}")
            lines.append("")
            continue
        desc = node.get("description")
        if desc:
            lines.append(desc)
            lines.append("")
        lines.append("```json")
        lines.append(json.dumps(node, indent=2, ensure_ascii=False))
        lines.append("```")
        lines.append("")
    return "\n".join(lines)


TARGETS = {
    "object_contracts.md": object_contracts_md,
    "v2_surface.md": v2_surface_md,
}


def render() -> Dict[str, str]:
    return {name: BANNER + fn() for name, fn in TARGETS.items()}


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if files on disk differ from generated output")
    parser.add_argument("--stdout", action="store_true",
                        help="print to stdout instead of writing")
    args = parser.parse_args(argv)

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    stale: List[str] = []
    for name, text in render().items():
        path = GENERATED_DIR / name
        if args.stdout:
            print(f"\n{'=' * 72}\n{name}\n{'=' * 72}\n{text}")
            continue
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                stale.append(name)
        elif current != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    if args.check and stale:
        print("Generated docs are STALE: " + ", ".join(stale), file=sys.stderr)
        print("Run: python scripts/gen_api_reference.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
