"""Regenerate the checked-in V2 API reference from executable FastAPI schemas."""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys
from tempfile import TemporaryDirectory
from typing import Any, Dict


REPOSITORY = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPOSITORY))

from measure_api.v2.app import create_app
from measure_api.v2.models import ServiceSettings
from measure_api.v2.registry import operations


def anchor(name: str) -> str:
    """Create a stable schema anchor.

    Args:
        name: Component name in the generated OpenAPI document.

    Returns:
        Lowercase identifier safe for a Markdown fragment.
    """
    return "schema-" + re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-")


def schema_type(schema: Dict[str, Any]) -> str:
    """Render linked types without discarding nullable or union alternatives.

    Args:
        schema: One OpenAPI schema node.

    Returns:
        Markdown type description referencing component definitions.
    """
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        return f"[{name}](#{anchor(name)})"
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            separator = " or " if key != "allOf" else " and "
            return separator.join(schema_type(item) for item in schema[key])
    if "const" in schema:
        return "`" + json.dumps(schema["const"]) + "`"
    if "enum" in schema:
        return ", ".join("`" + json.dumps(item) + "`" for item in schema["enum"])
    kind = schema.get("type", "any")
    if kind == "array":
        return "array of " + schema_type(schema.get("items", {}))
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        return "map of " + schema_type(schema["additionalProperties"])
    return kind


def field_table(schema: Dict[str, Any]) -> str:
    """Render actual required fields, defaults and declared schema constraints.

    Args:
        schema: Object schema from FastAPI components.

    Returns:
        Markdown table of all immediate fields, with linked nested types.
    """
    lines = ["| Field | Type | Required | Default | Constraints / description |",
             "|---|---|---|---|---|"]
    required = set(schema.get("required", []))
    keys = ("minimum", "exclusiveMinimum", "maximum", "exclusiveMaximum", "minLength",
            "maxLength", "minItems", "maxItems", "pattern", "format", "discriminator")
    for name, prop in schema.get("properties", {}).items():
        default = json.dumps(prop["default"]) if "default" in prop else "not declared"
        details = [f"{key}: {json.dumps(prop[key])}" for key in keys if key in prop]
        for union_key in ("anyOf", "oneOf", "allOf"):
            for index, variant in enumerate(prop.get(union_key, [])):
                details.extend(f"{union_key}[{index}] {key}: {json.dumps(variant[key])}"
                               for key in keys if key in variant)
        if prop.get("description"):
            details.append(prop["description"].replace("\n", " "))
        cells = [f"`{name}`", schema_type(prop), "yes" if name in required else "no",
                 f"`{default}`", "; ".join(details) or "—"]
        lines.append("| " + " | ".join(cell.replace("|", "&#124;") for cell in cells) + " |")
    return "\n".join(lines)


def main() -> None:
    """Export schemas and a linked reference without starting workers or accessing assets."""
    with TemporaryDirectory() as folder:
        app = create_app(ServiceSettings(shared_roots={"exchange": Path(folder)}))
        document = app.openapi()
    destination = REPOSITORY / "docs"
    (destination / "v2-openapi.json").write_text(
        json.dumps(document, indent=2, ensure_ascii=False, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    schemas = document["components"]["schemas"]
    manifest = json.loads((destination / "v2-required-routes.json").read_text())
    registry = {"/api/v2" + op.path: op for op in operations().values()}
    lines = [
        "# V2 API field reference", "",
        "Generated by `python docs/v2/generate_reference.py` from the executable FastAPI contract.",
        "Use [the upstream integration guide](v2-upstream-api.md) for lifecycle, file ownership,",
        "semantic rules and runnable examples. The [OpenAPI snapshot](v2-openapi.json) contains",
        "complete nested schemas; fetch `/api/v2/openapi.json` from the deployed service to verify",
        "its version. Model validators impose additional rules described in the guide/family docs.",
        "A nullable field can still be required. `not declared` means the schema has no literal",
        "default, including fields initialized by server-side factories; it is not a sent value.",
        "Defaults and constraints below come directly from the schema rather than inferred values.",
        "Calculation responses wrap their result in OperationResponse;",
        "inspect both state and validity.",
        "", "## Route index", "", "65 required routes, including 55 calculation operations.",
        "Documentation/schema endpoints are served by FastAPI but excluded from its paths list.",
        "", "| Family | Method | Route | Calculation ID |", "|---|---|---|---|",
    ]
    for item in manifest:
        op = registry.get(item["path"])
        link = "route-" + re.sub(r"[^a-z0-9]+", "-", item["path"].lower()).strip("-")
        lines.append(f"| {item['family']} | {item['method']} | "
                     f"[`{item['path']}`](#{link}) | `{op.operation_id if op else '—'}` |")
    lines.extend(["", "## Endpoint contracts", ""])
    for item in manifest:
        path = item["path"]
        link = "route-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")
        lines.extend([f'<a id="{link}"></a>', "", f"### {item['method']} `{path}`", ""])
        if path in registry:
            op = registry[path]
            api = document["paths"][path]["post"]
            request = api["requestBody"]["content"]["application/json"]["schema"]
            response = api["responses"]["200"]["content"]["application/json"]["schema"]
            lines.extend([op.summary + ".", "", f"Calculation ID: `{op.operation_id}`.", "",
                          f"Request: {schema_type(request)}. Response: {schema_type(response)}.",
                          "", "Named output ports (for recipe bindings):", "",
                          "```json", json.dumps(op.output_ports, indent=2), "```", "",
                          "Scheduling, errors and 200/202 behavior follow the shared guide.", ""])
        elif path.endswith("/docs"):
            lines.extend(["Returns Swagger UI HTML, not an operation or JSON result.", ""])
        elif path.endswith("/openapi.json"):
            lines.extend(["Returns the OpenAPI 3.1 schema without an operation envelope.", ""])
        else:
            normalized = path.replace("{id}", "{identity}")
            api = document["paths"][normalized][item["method"].lower()]
            lines.extend(["Control/discovery route; see the shared guide for semantics.", ""])
            if api.get("parameters"):
                lines.extend(["| Parameter | In | Type | Required | Default |",
                              "|---|---|---|---|---|"])
                for param in api["parameters"]:
                    prop = param["schema"]
                    lines.append(f"| `{param['name']}` | {param['in']} | {schema_type(prop)} | "
                                 f"{param.get('required', False)} | "
                                 f"`{json.dumps(prop.get('default'))}` |")
                lines.append("")
            response = api["responses"]["200"]["content"]["application/json"]["schema"]
            lines.extend([f"HTTP 200 schema: {schema_type(response)}.", ""])
    lines.extend(["## Schema catalog", "",
                  "Fields are immediate JSON properties; linked models describe nested values.",
                  "Strict typed models reject unknown fields and non-finite numeric values.", ""])
    for name, schema in sorted(schemas.items()):
        lines.extend([f'<a id="{anchor(name)}"></a>', "", f"### {name}", ""])
        if schema.get("description"):
            lines.extend([schema["description"], ""])
        if schema.get("properties"):
            lines.extend([field_table(schema), ""])
        else:
            lines.extend([schema_type(schema), ""])
    (destination / "v2-api-reference.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Exported {len(manifest)} routes, {len(registry)} calculations, {len(schemas)} schemas.")


if __name__ == "__main__":
    main()
